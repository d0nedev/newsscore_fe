import type { PlayerProfile, SquadPlayer, TeamProfile } from "~/types/match";

const squad = (prefix: string, names: string[]): SquadPlayer[] =>
  names.map((name, i) => ({
    id: `${prefix}-${i + 1}`,
    name,
    number: i + 1,
    position: (["GK", "DF", "DF", "MF", "MF", "MF", "FW", "FW"] as const)[
      i % 8
    ]!,
    age: 21 + ((i * 3) % 12),
    matches: 5 - (i % 3),
    goals: (i * 2) % 5,
    assists: i % 4,
  }));

